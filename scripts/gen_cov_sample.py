def generate_attrs_file(filename,fileContent):
    lines = []
    lines += generate_header(filename)
    lines.append(f'	function void sample(input cp_table table);')
    for enumName, enumVal in fileContent.items():
        lines += enumVal.sample()
    lines.append(f'	endfunction')
    lines += generate_footer()
    with open (f'{filename}','w') as outputFile:
        for line in lines:
            outputFile.write(line+"\n")

